-- T11 · Modelo físico dimensional en PostgreSQL
-- Ejecutar: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f sql/T11_modelo_fisico.sql
-- Requiere public.precipitacion (creada por sql/01_esquema.sql).
-- Los tiempos se deben medir en el entorno del equipo; no se inventan aquí.

BEGIN;
CREATE SCHEMA IF NOT EXISTS dw;

CREATE TABLE IF NOT EXISTS dw.dim_fecha (
  sk_fecha BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha DATE NOT NULL UNIQUE, anio SMALLINT NOT NULL, mes SMALLINT NOT NULL,
  nombre_mes TEXT NOT NULL, dia SMALLINT NOT NULL, dia_semana SMALLINT NOT NULL,
  es_fin_de_semana BOOLEAN NOT NULL, trimestre SMALLINT NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_hora_del_dia (
  sk_hora_del_dia SMALLINT PRIMARY KEY, hora_minuto TIME NOT NULL UNIQUE,
  hora SMALLINT NOT NULL, minuto SMALLINT NOT NULL, franja TEXT NOT NULL
);

-- SCD tipo 2: se conserva una fila por versión de estación.
CREATE TABLE IF NOT EXISTS dw.dim_estacion (
  sk_estacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigoestacion BIGINT NOT NULL, nombre_estacion TEXT, departamento TEXT,
  municipio TEXT, zona_hidrografica TEXT, latitud DOUBLE PRECISION,
  longitud DOUBLE PRECISION, vigente_desde TIMESTAMP NOT NULL,
  vigente_hasta TIMESTAMP, es_actual BOOLEAN NOT NULL DEFAULT TRUE,
  CHECK (vigente_hasta IS NULL OR vigente_hasta > vigente_desde)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_dim_estacion_actual
  ON dw.dim_estacion(codigoestacion) WHERE es_actual;
CREATE INDEX IF NOT EXISTS ix_dim_estacion_vigencia
  ON dw.dim_estacion(codigoestacion, vigente_desde, vigente_hasta);

-- SCD tipo 1: se sobrescribe la descripción corregida del sensor.
CREATE TABLE IF NOT EXISTS dw.dim_sensor (
  sk_sensor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigosensor BIGINT NOT NULL UNIQUE, descripcion_sensor TEXT, unidad_medida TEXT
);

CREATE TABLE IF NOT EXISTS dw.hechos_precipitacion (
  sk_fecha BIGINT NOT NULL REFERENCES dw.dim_fecha(sk_fecha),
  sk_hora_del_dia SMALLINT NOT NULL REFERENCES dw.dim_hora_del_dia(sk_hora_del_dia),
  sk_estacion BIGINT NOT NULL REFERENCES dw.dim_estacion(sk_estacion),
  sk_sensor BIGINT NOT NULL REFERENCES dw.dim_sensor(sk_sensor),
  valor_precipitacion_mm DOUBLE PRECISION,
  fechaobservacion TIMESTAMP NOT NULL,
  PRIMARY KEY (sk_estacion, sk_sensor, fechaobservacion)
);
CREATE INDEX IF NOT EXISTS ix_dw_hechos_fecha ON dw.hechos_precipitacion(sk_fecha);
CREATE INDEX IF NOT EXISTS ix_dw_hechos_estacion_fecha
  ON dw.hechos_precipitacion(sk_estacion, sk_fecha);

-- Muestra reproducible: hasta 10.000 filas reales. Si origen está vacío,
-- se usan tres filas sintéticas identificadas explícitamente como DEMO.
CREATE TEMP TABLE t11_muestra ON COMMIT DROP AS
SELECT codigoestacion, codigosensor, fechaobservacion, valorobservado,
       nombreestacion, departamento, municipio, zonahidrografica,
       latitud, longitud, descripcionsensor, unidadmedida
FROM public.precipitacion
ORDER BY fechaobservacion, codigoestacion, codigosensor
LIMIT 10000;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM t11_muestra) THEN
    INSERT INTO t11_muestra VALUES
    (99999901,240,'2026-06-22 08:00',2.4,'ESTACION DEMO T11','DEP DEMO','MUN DEMO','ZONA DEMO',4.6,-74.1,'PRECIPITACION DEMO','mm'),
    (99999901,240,'2026-06-22 08:01',3.1,'ESTACION DEMO T11','DEP DEMO','MUN DEMO','ZONA DEMO',4.6,-74.1,'PRECIPITACION DEMO','mm'),
    (99999902,257,'2026-06-22 08:00',0.7,'ESTACION DEMO T11 B','DEP DEMO','MUN DEMO B','ZONA DEMO',4.7,-74.2,'GPRS - PRECIPITACION DEMO','mm');
  END IF;
END $$;

INSERT INTO dw.dim_fecha(fecha,anio,mes,nombre_mes,dia,dia_semana,es_fin_de_semana,trimestre)
SELECT DISTINCT fechaobservacion::date, EXTRACT(YEAR FROM fechaobservacion)::smallint,
 EXTRACT(MONTH FROM fechaobservacion)::smallint, to_char(fechaobservacion,'TMMonth'),
 EXTRACT(DAY FROM fechaobservacion)::smallint, EXTRACT(ISODOW FROM fechaobservacion)::smallint,
 EXTRACT(ISODOW FROM fechaobservacion) IN (6,7), EXTRACT(QUARTER FROM fechaobservacion)::smallint
FROM t11_muestra ON CONFLICT(fecha) DO NOTHING;

INSERT INTO dw.dim_hora_del_dia(sk_hora_del_dia,hora_minuto,hora,minuto,franja)
SELECT m::smallint, make_time(m/60,m%60,0), (m/60)::smallint, (m%60)::smallint,
 CASE WHEN m<360 THEN 'madrugada' WHEN m<720 THEN 'mañana'
      WHEN m<1080 THEN 'tarde' ELSE 'noche' END
FROM generate_series(0,1439) AS g(m)
ON CONFLICT(sk_hora_del_dia) DO NOTHING;

-- Crea versiones cuando la fuente contiene cambios de atributos en el tiempo.
WITH variantes AS (
 SELECT codigoestacion,nombreestacion,departamento,municipio,zonahidrografica,latitud,longitud,
        min(fechaobservacion) AS desde
 FROM t11_muestra
 GROUP BY codigoestacion,nombreestacion,departamento,municipio,zonahidrografica,latitud,longitud
), ordenadas AS (
 SELECT v.*, lead(desde) OVER(PARTITION BY codigoestacion ORDER BY desde) AS hasta
 FROM variantes v
)
INSERT INTO dw.dim_estacion(codigoestacion,nombre_estacion,departamento,municipio,
 zona_hidrografica,latitud,longitud,vigente_desde,vigente_hasta,es_actual)
SELECT codigoestacion,nombreestacion,departamento,municipio,zonahidrografica,latitud,longitud,
 desde,hasta,(hasta IS NULL)
FROM ordenadas o
WHERE NOT EXISTS (SELECT 1 FROM dw.dim_estacion d
 WHERE d.codigoestacion=o.codigoestacion AND d.vigente_desde=o.desde);

-- Dos versiones de prueba separadas de los datos reales: garantiza evidencia SCD2.
DO $$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM dw.dim_estacion WHERE codigoestacion=99999999) THEN
  INSERT INTO dw.dim_estacion(codigoestacion,nombre_estacion,departamento,municipio,
   zona_hidrografica,latitud,longitud,vigente_desde,vigente_hasta,es_actual)
  VALUES
   (99999999,'ESTACION DEMO HISTORICA','DEPARTAMENTO ANTERIOR DEMO','MUNICIPIO DEMO','ZONA DEMO',4.6,-74.1,'2020-01-01','2025-01-01',FALSE),
   (99999999,'ESTACION DEMO HISTORICA','DEPARTAMENTO ACTUAL DEMO','MUNICIPIO DEMO','ZONA DEMO',4.6,-74.1,'2025-01-01',NULL,TRUE);
 END IF;
END $$;

INSERT INTO dw.dim_sensor(codigosensor,descripcion_sensor,unidad_medida)
SELECT codigosensor,max(descripcionsensor),max(unidadmedida)
FROM t11_muestra GROUP BY codigosensor
ON CONFLICT(codigosensor) DO NOTHING;

-- Tipo 1: corrección por sobrescritura, sin guardar una versión anterior.
UPDATE dw.dim_sensor
SET descripcion_sensor=upper(trim(descripcion_sensor))
WHERE descripcion_sensor IS NOT NULL
  AND descripcion_sensor<>upper(trim(descripcion_sensor));

INSERT INTO dw.hechos_precipitacion(sk_fecha,sk_hora_del_dia,sk_estacion,sk_sensor,
 valor_precipitacion_mm,fechaobservacion)
SELECT f.sk_fecha,h.sk_hora_del_dia,e.sk_estacion,s.sk_sensor,
 m.valorobservado,m.fechaobservacion
FROM t11_muestra m
JOIN dw.dim_fecha f ON f.fecha=m.fechaobservacion::date
JOIN dw.dim_hora_del_dia h ON h.hora_minuto=date_trunc('minute',m.fechaobservacion)::time
JOIN dw.dim_estacion e ON e.codigoestacion=m.codigoestacion
 AND m.fechaobservacion>=e.vigente_desde
 AND (e.vigente_hasta IS NULL OR m.fechaobservacion<e.vigente_hasta)
JOIN dw.dim_sensor s ON s.codigosensor=m.codigosensor
ON CONFLICT(sk_estacion,sk_sensor,fechaobservacion) DO NOTHING;

ANALYZE dw.dim_fecha; ANALYZE dw.dim_hora_del_dia;
ANALYZE dw.dim_estacion; ANALYZE dw.dim_sensor; ANALYZE dw.hechos_precipitacion;
COMMIT;

SELECT 'dim_fecha' tabla,count(*) filas FROM dw.dim_fecha
UNION ALL SELECT 'dim_hora_del_dia',count(*) FROM dw.dim_hora_del_dia
UNION ALL SELECT 'dim_estacion',count(*) FROM dw.dim_estacion
UNION ALL SELECT 'dim_sensor',count(*) FROM dw.dim_sensor
UNION ALL SELECT 'hechos_precipitacion',count(*) FROM dw.hechos_precipitacion;

SELECT codigoestacion,departamento,vigente_desde,vigente_hasta,es_actual
FROM dw.dim_estacion WHERE codigoestacion=99999999 ORDER BY vigente_desde;
